//! Shipment scope includes first publication without changing package source versions (#283).
use crate::{
    archive,
    context::{BUILD_TOOL_PACKAGE, BuildContext},
    error::{BuildError, BuildResult},
    published_history::{ArchiveOrigin, AssetHistory, HistoryReceipt, ReleaseIndex},
    release_scope::ReleaseScope,
    workspace::{CargoWorkspace, WorkspacePackage},
};
use serde::Serialize;
use std::{collections::BTreeMap, path::Path};

pub(crate) use crate::publication_record::PublicationReason;

#[derive(Debug, Serialize)]
pub(crate) struct PackagePublication {
    pub name: String,
    pub version: semver::Version,
    pub reason: PublicationReason,
    pub archive_sha256: Option<String>,
    pub origins: Vec<ArchiveOrigin>,
}

pub(crate) struct PublicationPlan {
    pub packages: BTreeMap<String, PackagePublication>,
    history: AssetHistory,
}

impl PublicationPlan {
    /// Selects verified reuse or first shipment; e.g. `PublicationPlan::load(context, workspace, scope, index)?`.
    pub fn load(
        context: &BuildContext<'_>,
        workspace: &CargoWorkspace,
        scope: &ReleaseScope,
        index: &ReleaseIndex,
    ) -> BuildResult<Self> {
        let history = AssetHistory::load(context, index)?;
        let mut packages = BTreeMap::new();
        for package in workspace
            .packages
            .iter()
            .filter(|package| package.name != BUILD_TOOL_PACKAGE)
        {
            let source_changed = scope.packages.contains(&package.name);
            let publication = select(package, source_changed, &history)?;
            packages.insert(package.name.clone(), publication);
        }
        Ok(Self { packages, history })
    }

    /// Lists only new assets, independent of affected tests; e.g. `plan.shipped_names()`.
    pub fn shipped_names(&self) -> Vec<String> {
        self.packages
            .values()
            .filter(|package| package.reason != PublicationReason::HistoricalReuse)
            .map(|package| package.name.clone())
            .collect()
    }

    /// Binds selected generated outputs before catalog publication; e.g. `plan.seal_outputs(dist)?;`.
    pub fn seal_outputs(&mut self, directory: &Path) -> BuildResult<()> {
        for name in self.shipped_names() {
            self.seal_output(&name, directory)?;
        }
        Ok(())
    }

    fn seal_output(&mut self, name: &str, directory: &Path) -> BuildResult<()> {
        let path = self.archive_path(name, directory)?;
        let package = self
            .packages
            .get_mut(name)
            .ok_or_else(|| failure(name, "a publication plan entry"))?;
        archive::verify_checksum(&path)?;
        crate::published_history::archive_manifest(&path, &package.name, &package.version)?;
        package.archive_sha256 = Some(archive::sha256_hex(&path)?);
        Ok(())
    }

    /// Resolves the selected bytes without guessing a release tag; e.g. `plan.archive_path(name, dist)?`.
    pub fn archive_path(&self, name: &str, directory: &Path) -> BuildResult<std::path::PathBuf> {
        let selected = self
            .packages
            .get(name)
            .ok_or_else(|| failure(name, "a publication plan entry"))?;
        if selected.reason != PublicationReason::HistoricalReuse {
            return Ok(directory.join(format!("{}-{}.crate", selected.name, selected.version)));
        }
        self.history
            .archives
            .get(&(selected.name.clone(), selected.version.clone()))
            .map(|archive| archive.path.clone())
            .ok_or_else(|| failure(name, "verified historical archive bytes"))
    }

    /// Supplies exact prior evidence to the release catalog; e.g. `plan.history_receipt()`.
    pub fn history_receipt(&self) -> &HistoryReceipt {
        &self.history.receipt
    }

    /// Refuses catalog publication before generated bytes are verified; e.g. `plan.require_sealed()?;`.
    pub fn require_sealed(&self) -> BuildResult<()> {
        for package in self.packages.values() {
            if package.archive_sha256.is_none() {
                return Err(failure(
                    &package.name,
                    "a verified archive digest before catalog publication",
                ));
            }
        }
        Ok(())
    }
}

fn select(
    package: &WorkspacePackage,
    source_changed: bool,
    history: &AssetHistory,
) -> BuildResult<PackagePublication> {
    let existing = history
        .archives
        .get(&(package.name.clone(), package.version.clone()));
    validate_reuse(package, source_changed, existing)?;
    let reason = match (existing.is_some(), source_changed) {
        (true, _) => PublicationReason::HistoricalReuse,
        (false, true) => PublicationReason::ChangedSource,
        (false, false) => PublicationReason::FirstPublication,
    };
    Ok(publication_record(package, reason, existing))
}

fn validate_reuse(
    package: &WorkspacePackage,
    source_changed: bool,
    existing: Option<&crate::published_history::PublishedArchive>,
) -> BuildResult<()> {
    if existing.is_some() && source_changed {
        return Err(failure(
            &format!("{}-{}", package.name, package.version),
            "a newer identity for changed package source",
        ));
    }
    if let Some(archive) = existing
        && archive::sha256_hex(&archive.path)? != archive.origins[0].sha256
    {
        return Err(failure(
            &archive.name,
            "unchanged verified historical bytes",
        ));
    }
    Ok(())
}

fn publication_record(
    package: &WorkspacePackage,
    reason: PublicationReason,
    existing: Option<&crate::published_history::PublishedArchive>,
) -> PackagePublication {
    PackagePublication {
        name: package.name.clone(),
        version: package.version.clone(),
        reason,
        archive_sha256: existing.map(|archive| archive.origins[0].sha256.clone()),
        origins: existing
            .map(|archive| archive.origins.clone())
            .unwrap_or_default(),
    }
}

fn failure(value: &str, expected: &str) -> BuildError {
    BuildError::ReleaseRule(format!("publication {value:?}; expected {expected}"))
}

