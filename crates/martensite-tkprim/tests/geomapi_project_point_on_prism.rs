//! Exact original elliptical-prism setup for the hosted surface-projection regression.
#![allow(non_snake_case, clippy::excessive_precision)]
use martensite_tkbrep::{brep::BRepTool, topexp::Explorer, topods, topods::Wire};
use martensite_tkernel::standard::Handle;
use martensite_tkg3d::{
    geom::{GeomCurve, GeomEllipse, GeomSurface},
    top_abs::ShapeEnum,
};
use martensite_tkgeomalgo::geom_api::ProjectPointOnSurf;
use martensite_tkgeombase::extrema::{ExtAlgo, ExtFlag};
use martensite_tkmath::gp::{Axis2, Direction3, Point3, Vector3};
use martensite_tkprim::brep_prim_api::BRepPrimAPIMakePrism;
use martensite_tktopalgo::brep_builder_api::{
    BRepBuilderAPIMakeEdge, BRepBuilderAPIMakeShape, BRepBuilderAPIMakeWire,
};

fn original_elliptical_wire() -> Wire {
    let origin = Point3::new(0., 0., 0.);
    let normal = Direction3::new(0., 0., 1.).unwrap();
    let frame = Axis2::new(origin, normal).unwrap();
    let ellipse: Handle<dyn GeomCurve> =
        Handle::new(GeomEllipse::new(frame, 10., 5.).unwrap()).cast();
    let edge = BRepBuilderAPIMakeEdge::from_curve(&ellipse)
        .unwrap()
        .edge()
        .unwrap();
    BRepBuilderAPIMakeWire::from_edge(&edge)
        .unwrap()
        .wire()
        .unwrap()
}

fn original_prism_first_face_surface() -> Handle<dyn GeomSurface> {
    let wire = original_elliptical_wire();
    let mut builder =
        BRepPrimAPIMakePrism::new(&wire, Vector3::new(2., 0., 30.), false, true).unwrap();
    let prism = builder.shape().unwrap();
    let explorer = Explorer::new(prism, ShapeEnum::Face, ShapeEnum::Shape).unwrap();
    assert!(explorer.more());
    let face = topods::face(explorer.current()).unwrap();
    let (surface, _location) = BRepTool::surface_with_location(&face).unwrap();
    assert!(!surface.is_null());
    surface
}

fn assert_original_projection(aProjector: &ProjectPointOnSurf) {
    assert!(aProjector.is_done());
    assert!(aProjector.nb_points().unwrap() > 0);

    let (aU, aV) = aProjector.lower_distance_parameters().unwrap();
    let aProjectedPoint = aProjector.nearest_point().unwrap();
    assert!((aProjector.lower_distance().unwrap() - 9.16061678111512e-10).abs() <= 1.0e-7);
    assert!((aU - 1.4954178490327235).abs() <= 1.0e-7);
    assert!((aV - 0.0).abs() <= 1.0e-7);
    assert!((aProjectedPoint.x() - 0.75307115689421944).abs() <= 1.0e-7);
    assert!((aProjectedPoint.y() - 4.9858019383179632).abs() <= 1.0e-7);
    assert!((aProjectedPoint.z() - 0.0).abs() <= 1.0e-7);
}

// Regression case `bugs_moddata_3::bug24138`. Projecting a point onto the
// lateral face generated by an elliptical wire must return stable UV and XYZ.
#[test]
fn GeomAPI_ProjectPointOnSurfTest__OCC24138_ProjectPointOnEllipticalPrismFace() {
    let aSurface = original_prism_first_face_surface();
    let aPoint = Point3::new(0.753071156928785, 4.98580193823337, 0.0);
    let (aUMin, aUMax, aVMin, aVMax) = aSurface.bounds();
    let mut aProjector = ProjectPointOnSurf::new();
    aProjector
        .init_surface(&aSurface, (aUMin, aUMax, aVMin, aVMax), ExtAlgo::Grad)
        .unwrap();
    aProjector.set_extrema_algo(ExtAlgo::Grad);
    aProjector.set_extrema_flag(ExtFlag::MinMax);
    aProjector.perform(aPoint).unwrap();
    assert_original_projection(&aProjector);
}
