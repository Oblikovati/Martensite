/// Runs the statements.
pub(super) fn define_statics() -> Result<(), Failure> {
    for row in ROWS {
        match row {
            Row::Init(family, name, kind, init) => {
                InterfaceStatic::init_char(family, name, *kind, init)?;
            }
            Row::Text(name, value) => {
                InterfaceStatic::set_c_val(name, value)?;
            }
            Row::Int(name, value) => {
                InterfaceStatic::set_i_val(name, *value)?;
            }
        }
    }
    Ok(())
}
