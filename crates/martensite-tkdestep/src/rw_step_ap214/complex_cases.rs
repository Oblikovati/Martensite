/// One way a complex entity can match.
#[derive(Clone, Copy)]
enum NamesTerm {
    /// The case of each name, in order.
    Exact(&'static [i32]),
    /// The cases each name may be, in order. An empty list takes any name.
    Ranks(&'static [&'static [i32]]),
}
use NamesTerm::{Exact, Ranks};

impl NamesTerm {
    /// Whether the names match, by `eq(rank, case)` from rank 1.
    fn matches(self, eq: &impl Fn(usize, i32) -> bool) -> bool {
        match self {
            Exact(cases) => cases
                .iter()
                .enumerate()
                .all(|(rank, case)| eq(rank + 1, *case)),
            Ranks(ranks) => ranks.iter().enumerate().all(|(rank, cases)| {
                cases.is_empty() || cases.iter().any(|case| eq(rank + 1, *case))
            }),
        }
    }
}

