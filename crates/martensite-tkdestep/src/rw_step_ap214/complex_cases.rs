/// The case of the first rule that matches, 0 when none does.
fn first_match(rules: CaseRules, eq: &impl Fn(usize, i32) -> bool) -> i32 {
    rules
        .iter()
        .find(|(_, terms)| terms.iter().any(|term| term.matches(eq)))
        .map_or(0, |(case, _)| *case)
}

/// The case of sorted names, 0 when not recognized. `eq(rank, case)` tests a name, from rank 1, against the
/// type name of a case.
pub(super) fn complex_case(count: usize, eq: &impl Fn(usize, i32) -> bool) -> i32 {
    match count {
        8 => first_match(RULES_OF_8, eq),
        7 => first_match(RULES_OF_7, eq),
        6 => first_match(RULES_OF_6, eq),
        5 => first_match(RULES_OF_5, eq),
        4 => first_match(RULES_OF_4, eq),
        3 => first_match(RULES_OF_3, eq),
        _ => 0,
    }
}
