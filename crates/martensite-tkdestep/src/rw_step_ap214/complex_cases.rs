/// The case of sorted names, 0 when not recognized. `eq(rank, case)` tests a name, from rank 1, against the
/// type name of a case.
pub(super) fn complex_case(
    count: usize,
    eq: &impl Fn(usize, i32) -> bool,
    eq_text: &impl Fn(usize, &str) -> bool,
) -> i32 {
    match count {
        8 => case_of_8(eq, eq_text),
        7 => case_of_7(eq, eq_text),
        6 => case_of_6(eq, eq_text),
        5 => case_of_5(eq, eq_text),
        4 => case_of_4(eq, eq_text),
        3 => case_of_3(eq, eq_text),
        _ => 0,
    }
}
