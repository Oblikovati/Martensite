/// The private fields of `StepDataFileRecognizer`; a recognizer embeds them.
#[derive(Default)]
pub struct StepDataFileRecognizerBase {
    state: SharedState<(
        Handle<StandardTransient>,
        Handle<dyn StepDataFileRecognizer>,
    )>,
}

/// `StepDataFileRecognizer`, abstract (`recognizer` instantiated): `eval` is
/// required and calls `set_ok` with an empty result of the type it recognises.
///
/// ```
/// use martensite_tkdestep::step_data::StepDataFileRecognizer;
/// fn first(reco: &dyn StepDataFileRecognizer) -> bool { reco.result().is_ok() }
/// ```
pub trait StepDataFileRecognizer: Transient {
    /// The embedded private fields.
    fn recognizer_base(&self) -> &StepDataFileRecognizerBase;
    /// `eval(akey)`.
    fn eval(&self, akey: &AsciiString);
    /// `evaluate(akey, res)`: its own `eval`, then the added recognizer's.
    fn evaluate(&self, akey: &AsciiString, res: &mut Handle<StandardTransient>) -> bool {
        self.set_ko();
        self.eval(akey);
        let (found, next) = {
            let state = self.recognizer_base().state.read();
            (state.0.clone(), state.1.clone())
        };
        if found.is_some() {
            *res = found;
            return true;
        }
        next.get().is_some_and(|live| live.evaluate(akey, res))
    }
    /// `result`: a no such object failure when the evaluation failed.
    fn result(&self) -> Result<Handle<StandardTransient>, Failure> {
        let (found, next) = {
            let state = self.recognizer_base().state.read();
            (state.0.clone(), state.1.clone())
        };
        if found.is_some() {
            return Ok(found);
        }
        match next.get() {
            Some(live) => live.result(),
            None => Err(exceptions::no_such_object(
                "Recognizer evaluation has failed; expected a call of Evaluate to succeed first",
            )),
        }
    }
    /// `add(reco)`.
    fn add(&self, reco: &Handle<dyn StepDataFileRecognizer>) {
        self.recognizer_base().state.write().1 = reco.clone();
    }
    /// `set_ok(aresult)` (protected).
    fn set_ok(&self, aresult: &Handle<StandardTransient>) {
        self.recognizer_base().state.write().0 = aresult.clone();
    }
    /// `set_ko` (protected).
    fn set_ko(&self) {
        self.recognizer_base().state.write().0.nullify();
    }
}
impl_transient_interface!(
    dyn StepDataFileRecognizer,
    "StepDataFileRecognizer",
    StandardTransient
);
