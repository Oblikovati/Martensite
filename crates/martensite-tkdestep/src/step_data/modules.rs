/// `StepDataReadWriteModule`, abstract. The members common with `InterfaceReaderModule`
/// are generated by [`impl_step_read_write_module`].
///
/// ```
/// use martensite_tkdestep::step_data::StepDataReadWriteModule;
/// fn known(module: &dyn StepDataReadWriteModule) -> bool { module.is_complex(1) }
/// ```
pub trait StepDataReadWriteModule: InterfaceReaderModule {
    /// `case_step(atype)`: the case of a simple type, 0 when not recognised. It must agree
    /// with the protocol's `type_number`.
    fn case_step(&self, atype: &AsciiString) -> i32;
    /// `case_step(types)`: the case of a complex type; recognises nothing by default.
    fn case_step_complex(&self, _types: &[AsciiString]) -> i32 {
        0
    }
    /// `is_complex(CN)`.
    fn is_complex(&self, _cn: i32) -> bool {
        false
    }
    /// `step_type(CN)`: as written in a file; empty for a complex type or case 0.
    fn step_type(&self, cn: i32) -> &'static str;
    /// `short_type(CN)`: empty by default, the long form is then used.
    fn short_type(&self, _cn: i32) -> AsciiString {
        AsciiString::default()
    }
    /// `complex_type(CN, types)`: the types of a complex case, alphabetically; false when
    /// not complex.
    fn complex_type(&self, _cn: i32, _types: &mut Vec<AsciiString>) -> bool {
        false
    }
    /// `read_step(CN, data, num, ach, ent)`: fills `ent` from record `num`.
    fn read_step(
        &self,
        cn: i32,
        data: &Handle<StepDataStepReaderData>,
        num: i32,
        ach: &mut Handle<InterfaceCheck>,
        ent: &Handle<StandardTransient>,
    ) -> Result<(), Failure>;
    /// `WriteStep(CN, SW, ent)`.
    fn write_step(
        &self,
        cn: i32,
        sw: &mut StepDataStepWriter,
        ent: &Handle<StandardTransient>,
    ) -> Result<(), Failure>;
}
impl_transient_interface!(
    dyn StepDataReadWriteModule,
    "StepDataReadWriteModule",
    dyn InterfaceReaderModule
);

/// The `case_num(data, num)` of a read-write module.
pub fn step_module_case_num<M: StepDataReadWriteModule + ?Sized>(
    module: &M,
    data: &Handle<dyn InterfaceFileReaderData>,
    num: i32,
) -> i32 {
    let step = data.cast::<StepDataStepReaderData>();
    let Some(live) = step.get() else {
        return 0;
    };
    if !live.is_complex(num) {
        return module.case_step(&live.record_type(num));
    }
    let mut types = Vec::new();
    live.complex_type(num, &mut types);
    match types.as_slice() {
        [] => 0,
        [one] => module.case_step(one),
        many => module.case_step_complex(many),
    }
}

/// The `Read(CN, data, num, ach, ent)` of a read-write module: `read_step` for STEP
/// data, nothing otherwise.
pub fn step_module_read<M: StepDataReadWriteModule + ?Sized>(
    module: &M,
    casenum: i32,
    data: &Handle<dyn InterfaceFileReaderData>,
    num: i32,
    ach: &mut Handle<InterfaceCheck>,
    ent: &Handle<StandardTransient>,
) -> Result<(), Failure> {
    let step = data.cast::<StepDataStepReaderData>();
    if step.is_null() {
        return Ok(());
    }
    module.read_step(casenum, &step, num, ach, ent)
}

/// Implements `InterfaceReaderModule` for a `StepDataReadWriteModule` (inherited,
/// but the orphan rule forbids a blanket impl across the crates);
/// `impl_step_read_write_module!(RWHeaderSectionReadWriteModule);`.
#[macro_export]
macro_rules! impl_step_read_write_module {
    ($module:ty) => {
        impl martensite_tkxsbase::interface::InterfaceReaderModule for $module {
            fn case_num(
                &self,
                data: &martensite_tkernel::standard::Handle<
                    dyn martensite_tkxsbase::interface::InterfaceFileReaderData,
                >,
                num: i32,
            ) -> i32 {
                $crate::step_data::step_module_case_num(self, data, num)
            }
            fn read(
                &self,
                casenum: i32,
                data: &martensite_tkernel::standard::Handle<
                    dyn martensite_tkxsbase::interface::InterfaceFileReaderData,
                >,
                num: i32,
                ach: &mut martensite_tkernel::standard::Handle<
                    martensite_tkxsbase::interface::InterfaceCheck,
                >,
                ent: &martensite_tkernel::standard::Handle<
                    martensite_tkernel::standard::StandardTransient,
                >,
            ) -> Result<(), martensite_tkernel::standard::Failure> {
                $crate::step_data::step_module_read(self, casenum, data, num, ach, ent)
            }
        }
    };
}

