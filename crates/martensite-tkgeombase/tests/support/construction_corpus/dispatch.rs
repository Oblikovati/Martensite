pub fn run_values(operation: &str, values: &[f64]) -> Option<String> {
    if operation.starts_with("gt_") {
        let output = Output::default();
        return super::geom_tools::run(&output, operation, values).then(|| output.finish());
    }
    let (_, case) = OPERATIONS.iter().find(|(name, _)| *name == operation)?;
    let output = Output::default();
    case(&output, values);
    Some(output.finish())
}

