//! The GLSL text of the grid program.

/// The grid vertex stage.
pub(super) const GRID_VERT: &str = concat!(
    "\nconst vec2 gridPlane[3] = vec2[] (",
    "\n  vec2(-1.0, -1.0), vec2(3.0, -1.0), vec2(-1.0, 3.0));",
    "\nvoid main()",
    "\n{",
    "\n  vec2 aVertex = gridPlane[gl_VertexID];",
    "\n  vNdc        = aVertex;",
    "\n  gl_Position = vec4 (aVertex, 0.0, 1.0);",
    "\n}",
);

/// The grid fragment stage.
pub(super) const GRID_FRAG: &str = concat!(
    "\nfloat gridLine1d (float theCoord, float theShift, float theScale, float theThickness)",
    "\n{",
    "\n  float aCoord = (theCoord - theShift) * theScale;",
    "\n  float aPixelWidth = fwidth (aCoord);",
    "\n  if (!(aPixelWidth >= 0.0)) { return 0.0; }",
    "\n  float aDist  = abs (fract (aCoord + 0.5) - 0.5);",
    "\n  float aWidth = max (aPixelWidth, theThickness);",
    "\n  if (aWidth == 0.0) { return 0.0; }",
    "\n  return 1.0 - min (aDist / aWidth, 1.0);",
    "\n}",
    "\nfloat axisLine1d (float theCoord, float theThickness)",
    "\n{",
    "\n  float aWidth = max (fwidth (theCoord), theThickness);",
    "\n  if (aWidth == 0.0) { return 0.0; }",
    "\n  return 1.0 - min (abs (theCoord) / aWidth, 1.0);",
    "\n}",
    "\nvec4 gridLines2d (vec2 theUV, vec2 theAxisUV, vec3 theColor, vec2 theScale,",
    "\n                  vec2 theShift, bool theIsDrawAxis, float theThickness)",
    "\n{",
    "\n  float aAlphaX = gridLine1d (theUV.x, theShift.x, theScale.x, theThickness);",
    "\n  float aAlphaY = gridLine1d (theUV.y, theShift.y, theScale.y, theThickness);",
    "\n  float aAlpha  = uDrawMode == 1 ? aAlphaX * aAlphaY : max (aAlphaX, aAlphaY);",
    "\n  vec4  aColor  = vec4 (theColor, aAlpha);",
    "\n  if (uIsDrawAxis != 0 && theIsDrawAxis && uDrawMode != 1)",
    "\n  {",
    "\n    float anAxisX = axisLine1d (theAxisUV.y, theThickness);",
    "\n    float anAxisY = axisLine1d (theAxisUV.x, theThickness);",
    "\n    if      (anAxisX > 0.0 && anAxisY > 0.0) { aColor = vec4 (0.0, 0.0, 1.0, max (aColor.a, max (anAxisX, anAxisY))); }",
    "\n    else if (anAxisX > 0.0)                  { aColor = vec4 (1.0, 0.0, 0.0, max (aColor.a, anAxisX)); }",
    "\n    else if (anAxisY > 0.0)                  { aColor = vec4 (0.0, 1.0, 0.0, max (aColor.a, anAxisY)); }",
    "\n  }",
    "\n  return aColor;",
    "\n}",
    "\nvec4 gridLines1d (float theCoord, float theShift, float theScale, vec3 theColor, float theThickness)",
    "\n{",
    "\n  return vec4 (theColor, gridLine1d (theCoord, theShift, theScale, theThickness));",
    "\n}",
    "\nvec4 overlayGrid (vec4 theBase, vec4 theAccent)",
    "\n{",
    "\n  return theAccent.a >= theBase.a ? theAccent : theBase;",
    "\n}",
    "\nvec3 unprojectView (float theX, float theY, float theZ)",
    "\n{",
    "\n  vec4 aView = occProjectionMatrixInverse * vec4 (theX, theY, theZ, 1.0);",
    "\n  return aView.xyz / aView.w;",
    "\n}",
    "\nfloat gridNdcNear()",
    "\n{",
    "\n  return uIsZeroToOneDepth != 0 ? 0.0 : -1.0;",
    "\n}",
    "\nfloat gridDepthFromNdc (float theNdcZ)",
    "\n{",
    "\n  return uIsZeroToOneDepth != 0 ? theNdcZ : (theNdcZ * 0.5 + 0.5);",
    "\n}",
    "\nfloat fragmentDepthFromView (vec3 theViewPnt)",
    "\n{",
    "\n  vec4 aClip = occProjectionMatrix * vec4 (theViewPnt, 1.0);",
    "\n  float aNdcZ = aClip.z / aClip.w;",
    "\n  return gridDepthFromNdc (aNdcZ);",
    "\n}",
    "\nbool intersectPlaneView (vec3 theNearPoint, vec3 theFarPoint, out vec3 theHit)",
    "\n{",
    "\n  vec3 aRayOrigin = uIsPerspective != 0 ? vec3 (0.0) : theNearPoint;",
    "\n  vec3 aRayTarget = theFarPoint;",
    "\n  vec3 aDir = aRayTarget - aRayOrigin;",
    "\n  float aDirLen = length (aDir);",
    "\n  if (aDirLen == 0.0) { return false; }",
    "\n  float aDenomN = dot (uPlaneNView, aDir / aDirLen);",
    "\n  if (abs (aDenomN) <= uParallelTolerance) { return false; }",
    "\n  float aDenom = dot (uPlaneNView, aDir);",
    "\n  float aT = dot (uPlaneNView, uPlaneOriginView - aRayOrigin) / aDenom;",
    "\n  if (uIsBackground == 0 && uIsPerspective != 0 && aT < 0.0)",
    "\n  {",
    "\n    theHit = theNearPoint;",
    "\n    return false;",
    "\n  }",
    "\n  theHit = aRayOrigin + aT * aDir;",
    "\n  return true;",
    "\n}",
    "\n",
    "\nconst float GRID_TWO_PI = 6.28318530718;",
    "\nfloat gridNormalizeAngle (float theAngle)",
    "\n{",
    "\n  float anAngle = mod (theAngle, GRID_TWO_PI);",
    "\n  if (anAngle < 0.0) { anAngle += GRID_TWO_PI; }",
    "\n  return anAngle;",
    "\n}",
    "\nfloat gridPositiveAngleSpan (float theStart, float theEnd)",
    "\n{",
    "\n  float aSpan = mod (theEnd - theStart, GRID_TWO_PI);",
    "\n  if (aSpan < 0.0) { aSpan += GRID_TWO_PI; }",
    "\n  if (abs (aSpan) <= uParallelTolerance && abs (theEnd - theStart) >= GRID_TWO_PI - uParallelTolerance)",
    "\n  {",
    "\n    return GRID_TWO_PI;",
    "\n  }",
    "\n  return aSpan;",
    "\n}",
    "\nbool gridAngleInArc (float theAngle)",
    "\n{",
    "\n  float aSpan = gridPositiveAngleSpan (uArcRange.x, uArcRange.y);",
    "\n  if (aSpan >= GRID_TWO_PI - uParallelTolerance) { return true; }",
    "\n  float aDelta = gridNormalizeAngle (theAngle) - gridNormalizeAngle (uArcRange.x);",
    "\n  if (aDelta < 0.0) { aDelta += GRID_TWO_PI; }",
    "\n  return aDelta <= aSpan + uParallelTolerance;",
    "\n}",
    "\nvoid main()",
    "\n{",
    "\n  vec3 aNearPoint = unprojectView (vNdc.x, vNdc.y, gridNdcNear());",
    "\n  vec3 aFarPoint  = unprojectView (vNdc.x, vNdc.y, 1.0);",
    "\n  vec3 aHit;",
    "\n  if (!intersectPlaneView (aNearPoint, aFarPoint, aHit)) { discard; }",
    "\n  float aFragDepth = fragmentDepthFromView (aHit);",
    "\n  if (uIsBackground == 0)",
    "\n  {",
    "\n    if (aFragDepth < 0.0) { discard; }",
    "\n    gl_FragDepth = min (aFragDepth, 1.0);",
    "\n  }",
    "\n  else",
    "\n  {",
    "\n    gl_FragDepth = 1.0;",
    "\n  }",
    "\n  vec3 aLocalAbs3  = aHit - uPlaneOriginView;",
    "\n  vec2 aLocal      = vec2 (dot (aLocalAbs3, uPlaneXView), dot (aLocalAbs3, uPlaneYView));",
    "\n  vec3 aLocalGrid3 = aHit - uPlaneRefView;",
    "\n  vec2 aLocalGrid  = vec2 (dot (aLocalGrid3, uPlaneXView), dot (aLocalGrid3, uPlaneYView));",
    "\n  float aR = length (aLocal);",
    "\n  float aA = atan (aLocal.y, aLocal.x);",
    "\n  float aBoundFade = 1.0;",
    "\n  if (uBounds.z > 0.0)",
    "\n  {",
    "\n    float aFwBR = fwidth (aR);",
    "\n    if (aR > uBounds.z) { discard; }",
    "\n    if (uIsBoundFade != 0)",
    "\n    {",
    "\n      aBoundFade *= 1.0 - smoothstep (uBounds.z - aFwBR, uBounds.z, aR);",
    "\n    }",
    "\n  }",
    "\n  if (uArcBounded != 0 && !gridAngleInArc (aA)) { discard; }",
    "\n  if (uBounds.x > 0.0)",
    "\n  {",
    "\n    float aFwBX = fwidth (abs (aLocal.x));",
    "\n    if (abs (aLocal.x) > uBounds.x) { discard; }",
    "\n    if (uIsBoundFade != 0)",
    "\n    {",
    "\n      aBoundFade *= 1.0 - smoothstep (uBounds.x - aFwBX, uBounds.x, abs (aLocal.x));",
    "\n    }",
    "\n  }",
    "\n  if (uBounds.y > 0.0)",
    "\n  {",
    "\n    float aFwBY = fwidth (abs (aLocal.y));",
    "\n    if (abs (aLocal.y) > uBounds.y) { discard; }",
    "\n    if (uIsBoundFade != 0)",
    "\n    {",
    "\n      aBoundFade *= 1.0 - smoothstep (uBounds.y - aFwBY, uBounds.y, abs (aLocal.y));",
    "\n    }",
    "\n  }",
    "\n  vec2 aGridUv;",
    "\n  vec2 aScale;",
    "\n  vec2 aAxisUv;",
    "\n  if (uGridType == 1)",
    "\n  {",
    "\n    aGridUv = vec2 (aR, aA);",
    "\n    aScale  = vec2 (uScaleX, uAngularScale);",
    "\n    aAxisUv = aLocal;",
    "\n  }",
    "\n  else",
    "\n  {",
    "\n    aGridUv = aLocalGrid;",
    "\n    aScale  = vec2 (uScaleX, uScaleY);",
    "\n    aAxisUv = aLocal;",
    "\n  }",
    "\n  vec2 aGridShift = uGridType == 1 ? vec2 (uRadialOriginShift, 0.0) : vec2 (0.0);",
    "\n  vec4 aColor = gridLines2d (aGridUv, aAxisUv, uColor, aScale, aGridShift, uGridType == 0, uThickness);",
    "\n  if (uDrawMode != 1)",
    "\n  {",
    "\n    if (uGridType == 0)",
    "\n    {",
    "\n      if (uAccentScaleX > 0.0)",
    "\n      {",
    "\n        aColor = overlayGrid (aColor, gridLines1d (aLocal.x, uAccentLocalOriginShift.x, uAccentScaleX, uAccentColor, uThickness));",
    "\n      }",
    "\n      if (uAccentScaleY > 0.0)",
    "\n      {",
    "\n        aColor = overlayGrid (aColor, gridLines1d (aLocal.y, uAccentLocalOriginShift.y, uAccentScaleY, uAccentColor, uThickness));",
    "\n      }",
    "\n    }",
    "\n    else",
    "\n    {",
    "\n      if (uAccentScaleX > 0.0)",
    "\n      {",
    "\n        aColor = overlayGrid (aColor, gridLines1d (aR, uAccentRadialOriginShift, uAccentScaleX, uAccentColor, uThickness));",
    "\n      }",
    "\n      if (uAccentAngularScale > 0.0)",
    "\n      {",
    "\n        aColor = overlayGrid (aColor, gridLines1d (aA, 0.0, uAccentAngularScale, uAccentColor, uThickness));",
    "\n      }",
    "\n    }",
    "\n    if (uIsDrawAxis != 0 && uGridType == 1)",
    "\n    {",
    "\n      float anAxisX = axisLine1d (aAxisUv.y, uThickness);",
    "\n      float anAxisY = axisLine1d (aAxisUv.x, uThickness);",
    "\n      if (anAxisX > 0.0 && anAxisY > 0.0)",
    "\n      {",
    "\n        aColor = vec4 (0.0, 0.0, 1.0, 1.0);",
    "\n      }",
    "\n      else if (anAxisX > 0.0)",
    "\n      {",
    "\n        aColor = vec4 (1.0, 0.0, 0.0, max (aColor.a, anAxisX));",
    "\n      }",
    "\n      else if (anAxisY > 0.0)",
    "\n      {",
    "\n        aColor = vec4 (0.0, 1.0, 0.0, max (aColor.a, anAxisY));",
    "\n      }",
    "\n    }",
    "\n  }",
    "\n  if (aColor.a == 0.0) { discard; }",
    "\n  aColor.a *= aBoundFade;",
    "\n  occFragColor = aColor;",
    "\n}",
);
