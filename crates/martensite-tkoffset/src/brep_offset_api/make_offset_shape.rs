//! `BRepOffsetAPIMakeOffsetShape` and `BRepOffsetAPIMakeThickSolid`: the offset shape
//! and the thick solid of a shape, by the join algorithm (`BRepOffsetMakeOffset`) or
//! the simple one (`BRepOffsetMakeSimpleOffset`).
use crate::brep_offset::{BRepOffsetMakeOffset, BRepOffsetMakeSimpleOffset, MakeOffsetOptions};
use martensite_tkbrep::topods::{self, Shape};
use martensite_tkernel::message::ProgressRange;
use martensite_tkernel::ncollection::List;
use martensite_tkernel::standard::Failure;
use martensite_tkmath::geom_abs::JoinType;
use martensite_tktopalgo::brep_builder_api::{
    BRepBuilderAPIMakeShape, BRepBuilderAPIMakeShapeBase,
};

/// The last algorithm used (`Type`).
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub enum OffsetAlgo {
    /// No offset algorithm has run; `OffsetAlgo::none`.
    #[default]
    None,
    /// The intersection/join algorithm; `OffsetAlgo::join`.
    Join,
    /// The simple surface-offset algorithm; `OffsetAlgo::simple`.
    Simple,
}

/// `BRepOffsetAPIMakeOffsetShape`: the offset shape of a shape by the join or the
/// simple algorithm;
///
/// ```
/// use martensite_tkbrep::topods::Shape;
/// use martensite_tkoffset::brep_offset_api::BRepOffsetAPIMakeOffsetShape;
/// use martensite_tktopalgo::brep_builder_api::BRepBuilderAPIMakeShape;
/// let mut maker = BRepOffsetAPIMakeOffsetShape::new();
/// maker.perform_by_simple(&Shape::default(), 1.0)?;
/// assert!(!maker.is_done());
/// # Ok::<(), martensite_tkernel::standard::Failure>(())
/// ```
pub struct BRepOffsetAPIMakeOffsetShape {
    base: BRepBuilderAPIMakeShapeBase,
    /// Algorithm selection for extension adapters; `maker.my_last_used_algo = OffsetAlgo::none`.
    pub my_last_used_algo: OffsetAlgo,
    /// Join-algorithm state for extension adapters; `maker.my_offset_shape.is_done()`.
    pub my_offset_shape: BRepOffsetMakeOffset,
    /// Simple-algorithm state for extension adapters; `maker.my_simple_offset_shape.offset_value()`.
    pub my_simple_offset_shape: BRepOffsetMakeSimpleOffset,
}

impl Default for BRepOffsetAPIMakeOffsetShape {
    fn default() -> Self {
        Self::new()
    }
}

impl BRepBuilderAPIMakeShape for BRepOffsetAPIMakeOffsetShape {
    fn make_shape_base(&self) -> &BRepBuilderAPIMakeShapeBase {
        &self.base
    }

    fn make_shape_base_mut(&mut self) -> &mut BRepBuilderAPIMakeShapeBase {
        &mut self.base
    }

    /// Nothing; the algorithms run in their Perform methods.
    fn build(&mut self, _range: &ProgressRange<'_>) -> Result<(), Failure> {
        Ok(())
    }

    /// The shapes generated by the join algorithm, or the shape
    /// generated by the simple one when it differs from the shape.
    fn generated(&mut self, shape: &Shape) -> Result<&List<Shape>, Failure> {
        self.base.my_generated.clear();
        match self.my_last_used_algo {
            OffsetAlgo::Join => {
                let g = self.my_offset_shape.generated(shape)?.clone();
                self.base.my_generated = g;
            }
            OffsetAlgo::Simple => {
                let a_gen_shape = self.my_simple_offset_shape.generated(shape)?;
                if !a_gen_shape.is_null() && !a_gen_shape.is_same(shape) {
                    self.base.my_generated.append(a_gen_shape);
                }
            }
            OffsetAlgo::None => {}
        }
        Ok(&self.base.my_generated)
    }

    /// The shapes modified by the join algorithm, or the shape modified
    /// by the simple one when it differs from the shape.
    fn modified(&mut self, shape: &Shape) -> Result<&List<Shape>, Failure> {
        self.base.my_generated.clear();
        match self.my_last_used_algo {
            OffsetAlgo::Join => {
                let m = self.my_offset_shape.modified(shape)?.clone();
                self.base.my_generated = m;
            }
            OffsetAlgo::Simple => {
                let a_gen_shape = self.my_simple_offset_shape.modified(shape)?;
                if !a_gen_shape.is_null() && !a_gen_shape.is_same(shape) {
                    self.base.my_generated.append(a_gen_shape);
                }
            }
            OffsetAlgo::None => {}
        }
        Ok(&self.base.my_generated)
    }

    /// The deletion by the join algorithm; false otherwise.
    fn is_deleted(&mut self, shape: &Shape) -> Result<bool, Failure> {
        if self.my_last_used_algo == OffsetAlgo::Join {
            return self.my_offset_shape.is_deleted(shape);
        }
        Ok(false)
    }
}

impl BRepOffsetAPIMakeOffsetShape {
    /// No algorithm run and a null result;
    /// `BRepOffsetAPIMakeOffsetShape::new()`.
    pub fn new() -> Self {
        Self {
            base: BRepBuilderAPIMakeShapeBase::new(),
            my_last_used_algo: OffsetAlgo::None,
            my_offset_shape: BRepOffsetMakeOffset::new(),
            my_simple_offset_shape: BRepOffsetMakeSimpleOffset::new(),
        }
    }

    /// The simple algorithm, its result kept
    /// when done; `maker.perform_by_simple(&shape, 10.0)?`.
    pub fn perform_by_simple(
        &mut self,
        the_s: &Shape,
        the_offset_value: f64,
    ) -> Result<(), Failure> {
        self.base.set_not_done();
        self.my_last_used_algo = OffsetAlgo::Simple;
        self.my_simple_offset_shape
            .initialize(the_s, the_offset_value);
        self.my_simple_offset_shape.perform()?;
        if !self.my_simple_offset_shape.is_done() {
            return Ok(());
        }
        self.base.my_shape = self.my_simple_offset_shape.result_shape().clone();
        self.base.set_done();
        Ok(())
    }

    /// `perform_by_join(S, Offset, Tol, Mode, Intersection, SelfInter, Join,
    /// RemoveIntEdges, Range)`: the join algorithm, its result kept when done (the
    /// defaulted arguments are MakeOffsetOptions, whose thickening flag is ignored);
    /// `maker.perform_by_join(&shape, 1.0, 1e-7, MakeOffsetOptions::default(), &range)?`.
    pub fn perform_by_join(
        &mut self,
        s: &Shape,
        offset: f64,
        tol: f64,
        options: MakeOffsetOptions,
        the_range: &ProgressRange,
    ) -> Result<(), Failure> {
        self.base.set_not_done();
        self.my_last_used_algo = OffsetAlgo::Join;
        self.my_offset_shape.initialize(
            s,
            offset,
            tol,
            MakeOffsetOptions {
                thickening: false,
                ..options
            },
        );
        self.my_offset_shape.make_offset_shape(the_range)?;
        if !self.my_offset_shape.is_done() {
            return Ok(());
        }
        self.base.my_shape = self.my_offset_shape.shape().clone();
        self.base.set_done();
        Ok(())
    }

    /// The join algorithm; `maker.make_offset()`.
    pub fn make_offset(&self) -> &BRepOffsetMakeOffset {
        &self.my_offset_shape
    }

    /// The join type of the join algorithm; `maker.get_join_type()`.
    pub fn get_join_type(&self) -> JoinType {
        self.my_offset_shape.get_join_type()
    }
}

/// `BRepOffsetAPIMakeThickSolid`: the thick solid of a shape (its faces offset and
/// joined to the shape through the removed closing faces), by the join or the simple
/// algorithm; `BRepOffsetAPIMakeThickSolid::new()`.
pub struct BRepOffsetAPIMakeThickSolid {
    inner: BRepOffsetAPIMakeOffsetShape,
}

impl Default for BRepOffsetAPIMakeThickSolid {
    fn default() -> Self {
        Self::new()
    }
}

impl BRepBuilderAPIMakeShape for BRepOffsetAPIMakeThickSolid {
    fn make_shape_base(&self) -> &BRepBuilderAPIMakeShapeBase {
        &self.inner.base
    }

    fn make_shape_base_mut(&mut self) -> &mut BRepBuilderAPIMakeShapeBase {
        &mut self.inner.base
    }

    /// Nothing; the algorithms run in their MakeThickSolid methods.
    fn build(&mut self, _range: &ProgressRange<'_>) -> Result<(), Failure> {
        Ok(())
    }

    fn generated(&mut self, shape: &Shape) -> Result<&List<Shape>, Failure> {
        self.inner.generated(shape)
    }

    /// The last offset images of a closing face (reversed) by the join
    /// algorithm, or the shape modified by the simple one.
    fn modified(&mut self, f: &Shape) -> Result<&List<Shape>, Failure> {
        let inner = &mut self.inner;
        inner.base.my_generated.clear();
        if inner.my_last_used_algo == OffsetAlgo::Join
            && inner
                .my_offset_shape
                .offset_faces_from_shapes()
                .has_image(f)
        {
            if inner.my_offset_shape.closing_faces().contains(f) {
                for mut s in inner
                    .my_offset_shape
                    .offset_faces_from_shapes()
                    .last_image(f)
                {
                    // The generated shapes reversed for small solids, useful only for
                    // the faces without influence on the others.
                    s.reverse();
                    inner.base.my_generated.append(s);
                }
            }
        } else if inner.my_last_used_algo == OffsetAlgo::Simple {
            let a_mod_shape = inner.my_simple_offset_shape.modified(f)?;
            if !a_mod_shape.is_null() {
                inner.base.my_generated.append(a_mod_shape);
            }
        }
        Ok(&inner.base.my_generated)
    }

    fn is_deleted(&mut self, shape: &Shape) -> Result<bool, Failure> {
        self.inner.is_deleted(shape)
    }
}

impl BRepOffsetAPIMakeThickSolid {
    /// The simple algorithm builds only solids;
    /// `BRepOffsetAPIMakeThickSolid::new()`.
    pub fn new() -> Self {
        let mut inner = BRepOffsetAPIMakeOffsetShape::new();
        inner.my_simple_offset_shape.set_build_solid_flag(true);
        Self { inner }
    }

    /// The simple algorithm, its result
    /// kept when done; `maker.make_thick_solid_by_simple(&face, 2.0)?`.
    pub fn make_thick_solid_by_simple(
        &mut self,
        the_s: &Shape,
        the_offset_value: f64,
    ) -> Result<(), Failure> {
        self.inner.perform_by_simple(the_s, the_offset_value)
    }

    /// `make_thick_solid_by_join(S, ClosingFaces, Offset, Tol, Mode, Intersection,
    /// SelfInter, Join, RemoveIntEdges, Range)`: the thick solid by the join algorithm
    /// with the closing faces removed (the defaulted arguments are MakeOffsetOptions,
    /// whose thickening flag is ignored); type_mismatch for a closing shape
    /// that is not a face;
    /// `maker.make_thick_solid_by_join(&solid, &faces, -1.0, 1e-7, MakeOffsetOptions::default(), &range)?`.
    pub fn make_thick_solid_by_join(
        &mut self,
        s: &Shape,
        closing_faces: &List<Shape>,
        offset: f64,
        tol: f64,
        options: MakeOffsetOptions,
        the_range: &ProgressRange,
    ) -> Result<(), Failure> {
        let inner = &mut self.inner;
        inner.base.set_not_done();
        inner.my_last_used_algo = OffsetAlgo::Join;
        inner.my_offset_shape.initialize(
            s,
            offset,
            tol,
            MakeOffsetOptions {
                thickening: false,
                ..options
            },
        );
        for f in closing_faces.iter() {
            inner.my_offset_shape.add_face(&topods::face(f)?);
        }
        inner.my_offset_shape.make_thick_solid(the_range)?;
        if !inner.my_offset_shape.is_done() {
            return Ok(());
        }
        inner.base.my_shape = inner.my_offset_shape.shape().clone();
        inner.base.set_done();
        Ok(())
    }

    /// The join algorithm; `maker.make_offset()`.
    pub fn make_offset(&self) -> &BRepOffsetMakeOffset {
        self.inner.make_offset()
    }

    /// An empty one; `maker.get_join_type()`.
    pub fn get_join_type(&self) -> JoinType {
        self.inner.get_join_type()
    }
}
